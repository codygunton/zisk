use std::{collections::HashSet, env, fs};

use zisk_core::{
    decode_and_lower_rv64im32, decode_rv64im32, Rv64imInst, Rv64imOp, StaticRow, StaticRows,
};

#[derive(Clone, Copy)]
struct Case {
    name: &'static str,
    word: u32,
}

const EXPECTED_VALID_CASES: usize = 71;
const EXPECTED_INVALID_CASES: usize = 3;
const EXPECTED_OPCODE_SURFACE: usize = 63;

fn main() {
    let args: Vec<_> = env::args().skip(1).collect();
    if args.is_empty() || args.len() > 3 {
        panic!(
            "usage: cargo run --example aeneas_bridge_cases -- <aeneas-output.lean> [main-output.lean] [cross-output.lean]"
        );
    }
    validate_manifest();
    fs::write(&args[0], aeneas_output()).expect("write Aeneas Lean case file");
    if let Some(path) = args.get(1) {
        fs::write(path, main_output()).expect("write main Lean case file");
    }
    if let Some(path) = args.get(2) {
        fs::write(path, cross_output()).expect("write cross-model Lean case file");
    }
}

fn aeneas_output() -> String {
    let mut out = String::new();
    out.push_str("import Rv64imExtract.Bridge\n\n");
    out.push_str("namespace Rv64imExtract.Bridge.GeneratedCases\n\n");
    out.push_str("/-!\n");
    out.push_str("This file is generated by zisk/core/examples/aeneas_bridge_cases.rs.\n");
    out.push_str("It checks Aeneas-extracted decode/lower behavior for canonical RV64IM\n");
    out.push_str("instruction words. Do not edit by hand.\n");
    out.push_str("-/\n\n");
    out.push_str(&format!("def rv64imValidCaseCount : Nat := {EXPECTED_VALID_CASES}\n"));
    out.push_str(&format!("def rv64imInvalidCaseCount : Nat := {EXPECTED_INVALID_CASES}\n\n"));

    for case in cases() {
        let rows = decode_and_lower_rv64im32(case.word, 0)
            .unwrap_or_else(|| panic!("case {} did not decode: 0x{:08x}", case.name, case.word));
        emit_case(&mut out, case, rows);
    }

    for (name, word) in [
        ("invalid_all_zero", 0x0000_0000),
        ("invalid_all_ones", 0xffff_ffffu32),
        ("invalid_compressed_width", 0x0000_0001),
    ] {
        out.push_str(&format!(
            "theorem decode_lower_{name} :\n    decodeLowerViews 0x{word:08x}#u32 = none := by\n  native_decide\n\n"
        ));
    }

    out.push_str("end Rv64imExtract.Bridge.GeneratedCases\n");
    out
}

fn main_output() -> String {
    let mut out = String::new();
    out.push_str("import ZiskFv.Transpiler.Static\n\n");
    out.push_str("open ZiskFv.Transpiler.Static\n\n");
    out.push_str("namespace ZiskFv.Transpiler.Static.GeneratedAeneasCases\n\n");
    out.push_str("/-!\n");
    out.push_str("This file is generated by zisk/core/examples/aeneas_bridge_cases.rs.\n");
    out.push_str("It checks the main Lean static transpiler on the same encoded-word\n");
    out.push_str("manifest used by the Aeneas extraction spike. Do not edit by hand.\n");
    out.push_str("-/\n\n");
    out.push_str(&format!("def rv64imValidCaseCount : Nat := {EXPECTED_VALID_CASES}\n\n"));

    for case in cases() {
        let inst = decode_rv64im32(case.word, 0)
            .unwrap_or_else(|| panic!("case {} did not decode: 0x{:08x}", case.name, case.word));
        let rows = decode_and_lower_rv64im32(case.word, 0)
            .unwrap_or_else(|| panic!("case {} did not lower: 0x{:08x}", case.name, case.word));
        emit_main_case(&mut out, case, inst, rows);
    }

    out.push_str("end ZiskFv.Transpiler.Static.GeneratedAeneasCases\n");
    out
}

fn cross_output() -> String {
    let mut out = String::new();
    out.push_str("import Rv64imExtract.Bridge\n");
    out.push_str("import ZiskFv.Transpiler.Static\n\n");
    out.push_str("namespace Rv64imExtract.Bridge.CrossModelCases\n\n");
    out.push_str("/-!\n");
    out.push_str("This file is generated by zisk/core/examples/aeneas_bridge_cases.rs.\n");
    out.push_str("It checks, in one Lean 4.28 package, that Aeneas-extracted\n");
    out.push_str("decode/lower rows match the main Lean static transpiler on the same\n");
    out.push_str("encoded-word manifest. Do not edit by hand.\n");
    out.push_str("-/\n\n");
    out.push_str(&format!("def rv64imValidCaseCount : Nat := {EXPECTED_VALID_CASES}\n\n"));
    out.push_str("def rowViewOfStatic (r : ZiskFv.Transpiler.Static.ZiskStaticRow) : RowView :=\n");
    out.push_str("  { paddr := r.paddr\n");
    out.push_str("    op := r.op\n");
    out.push_str("    aSrc := r.aSrc\n");
    out.push_str("    aUseSpImm1 := r.aUseSpImm1\n");
    out.push_str("    aOffsetImm0 := r.aOffsetImm0\n");
    out.push_str("    bSrc := r.bSrc\n");
    out.push_str("    bUseSpImm1 := r.bUseSpImm1\n");
    out.push_str("    bOffsetImm0 := r.bOffsetImm0\n");
    out.push_str("    store := r.store\n");
    out.push_str("    storeOffset := r.storeOffset\n");
    out.push_str("    storePc := r.storePc\n");
    out.push_str("    setPc := r.setPc\n");
    out.push_str("    indWidth := r.indWidth\n");
    out.push_str("    jmpOffset1 := r.jmpOffset1\n");
    out.push_str("    jmpOffset2 := r.jmpOffset2\n");
    out.push_str("    isExternalOp := r.isExternalOp\n");
    out.push_str("    m32 := r.m32 }\n\n");
    out.push_str("def rowsViewOfStatic (rows : List ZiskFv.Transpiler.Static.ZiskStaticRow) : List RowView :=\n");
    out.push_str("  rows.map rowViewOfStatic\n\n");

    for case in cases() {
        let inst = decode_rv64im32(case.word, 0)
            .unwrap_or_else(|| panic!("case {} did not decode: 0x{:08x}", case.name, case.word));
        emit_cross_case(&mut out, case, inst);
    }

    out.push_str("end Rv64imExtract.Bridge.CrossModelCases\n");
    out
}

fn validate_manifest() {
    let cases = cases();
    assert_eq!(
        cases.len(),
        EXPECTED_VALID_CASES,
        "update EXPECTED_VALID_CASES when changing the manifest"
    );

    let mut names = HashSet::new();
    let mut words = HashSet::new();
    let mut opcodes = HashSet::new();
    for case in &cases {
        assert!(names.insert(case.name), "duplicate case name {}", case.name);
        assert!(
            words.insert(case.word),
            "duplicate encoded word for case {}: 0x{:08x}",
            case.name,
            case.word
        );
        let inst = decode_rv64im32(case.word, 0)
            .unwrap_or_else(|| panic!("case {} did not decode: 0x{:08x}", case.name, case.word));
        opcodes.insert(lean_op(inst.op));
    }
    assert_eq!(
        opcodes.len(),
        EXPECTED_OPCODE_SURFACE,
        "manifest stopped covering the expected RV64IM opcode surface"
    );
}

fn emit_case(out: &mut String, case: Case, rows: StaticRows) {
    out.push_str(&format!("def expected_{} : List RowView :=\n", case.name));
    out.push_str("  ");
    emit_rows(out, rows.as_slice());
    out.push_str("\n\n");
    out.push_str(&format!(
        "theorem decode_lower_{} :\n    decodeLowerViews 0x{:08x}#u32 = some expected_{} := by\n  native_decide\n\n",
        case.name, case.word, case.name
    ));
}

fn emit_rows(out: &mut String, rows: &[StaticRow]) {
    out.push('[');
    for (idx, row) in rows.iter().enumerate() {
        if idx > 0 {
            out.push_str(",\n   ");
        }
        emit_row(out, row);
    }
    out.push(']');
}

fn emit_main_case(out: &mut String, case: Case, inst: Rv64imInst, rows: StaticRows) {
    out.push_str(&format!("def expected_{} : List ZiskStaticRow :=\n", case.name));
    out.push_str("  ");
    emit_main_rows(out, rows.as_slice());
    out.push_str("\n\n");
    out.push_str(&format!(
        "theorem transpile_{} :\n    transpile {{ paddr := {}, op := .{}, rd := {}, rs1 := {}, rs2 := {}, imm := {} }} = expected_{} := by\n  native_decide\n\n",
        case.name,
        inst.paddr,
        lean_op(inst.op),
        inst.rd,
        inst.rs1,
        inst.rs2,
        inst.imm,
        case.name
    ));
}

fn emit_cross_case(out: &mut String, case: Case, inst: Rv64imInst) {
    out.push_str(&format!(
        "theorem aeneas_eq_main_static_{} :\n    decodeLowerViews 0x{:08x}#u32 = some (rowsViewOfStatic (ZiskFv.Transpiler.Static.transpile {{ paddr := {}, op := .{}, rd := {}, rs1 := {}, rs2 := {}, imm := {} }})) := by\n  native_decide\n\n",
        case.name,
        case.word,
        inst.paddr,
        lean_op(inst.op),
        inst.rd,
        inst.rs1,
        inst.rs2,
        inst.imm,
    ));
}

fn emit_main_rows(out: &mut String, rows: &[StaticRow]) {
    out.push('[');
    for (idx, row) in rows.iter().enumerate() {
        if idx > 0 {
            out.push_str(",\n   ");
        }
        emit_main_row(out, row);
    }
    out.push(']');
}

fn emit_main_row(out: &mut String, row: &StaticRow) {
    out.push_str(&format!(
        "{{ paddr := {}\n     op := {}\n     aSrc := {}\n     aUseSpImm1 := {}\n     aOffsetImm0 := {}\n     bSrc := {}\n     bUseSpImm1 := {}\n     bOffsetImm0 := {}\n     store := {}\n     storeOffset := {}\n     storePc := {}\n     setPc := {}\n     indWidth := {}\n     jmpOffset1 := {}\n     jmpOffset2 := {}\n     isExternalOp := {}\n     m32 := {} }}",
        row.paddr,
        row.op,
        row.a_src,
        row.a_use_sp_imm1,
        row.a_offset_imm0,
        row.b_src,
        row.b_use_sp_imm1,
        row.b_offset_imm0,
        row.store,
        row.store_offset,
        lean_bool(row.store_pc),
        lean_bool(row.set_pc),
        row.ind_width,
        row.jmp_offset1,
        row.jmp_offset2,
        lean_bool(row.is_external_op),
        lean_bool(row.m32),
    ));
}

